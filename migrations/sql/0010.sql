CREATE OR REPLACE FUNCTION shiliu.validate_research_attempt_source() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE parent_task text; source_task text; source_attempt text; ancestor_found boolean;
BEGIN
  IF NEW.parent_attempt_id IS NULL THEN
    IF NEW.source_checkpoint_id IS NOT NULL THEN
      RAISE EXCEPTION 'research_attempt_source_lineage' USING ERRCODE='23503';
    END IF;
    RETURN NEW;
  END IF;
  SELECT task_id INTO parent_task FROM shiliu.research_attempts
    WHERE workspace_id=NEW.workspace_id AND attempt_id=NEW.parent_attempt_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'research_attempt_source_lineage' USING ERRCODE='23503'; END IF;
  IF NEW.source_checkpoint_id IS NOT NULL THEN
    SELECT task_id,attempt_id INTO source_task,source_attempt FROM shiliu.research_checkpoints
      WHERE workspace_id=NEW.workspace_id AND checkpoint_id=NEW.source_checkpoint_id;
    IF NOT FOUND OR source_task IS DISTINCT FROM parent_task OR source_attempt IS DISTINCT FROM NEW.parent_attempt_id THEN
      RAISE EXCEPTION 'research_attempt_source_lineage' USING ERRCODE='23503';
    END IF;
  END IF;
  IF parent_task=NEW.task_id THEN RETURN NEW; END IF;
  IF NEW.cause NOT IN ('branch','replay') OR NEW.source_checkpoint_id IS NULL THEN
    RAISE EXCEPTION 'research_attempt_source_lineage' USING ERRCODE='23503';
  END IF;
  WITH RECURSIVE ancestors AS (
    SELECT task_id,parent_task_id,owner_user_id,ARRAY[task_id] AS path FROM shiliu.research_tasks
      WHERE workspace_id=NEW.workspace_id AND task_id=NEW.task_id
    UNION ALL
    SELECT t.task_id,t.parent_task_id,t.owner_user_id,a.path||t.task_id FROM shiliu.research_tasks t
      JOIN ancestors a ON t.task_id=a.parent_task_id AND t.owner_user_id=a.owner_user_id
      WHERE t.workspace_id=NEW.workspace_id AND NOT t.task_id=ANY(a.path)
  ) SELECT EXISTS(SELECT 1 FROM ancestors WHERE task_id=parent_task) INTO ancestor_found;
  IF NOT ancestor_found THEN
    SELECT EXISTS(
      SELECT 1 FROM shiliu.research_task_derivations d
      JOIN shiliu.research_tasks source ON (source.workspace_id,source.task_id)=(d.workspace_id,d.source_task_id)
      JOIN shiliu.research_tasks child ON (child.workspace_id,child.task_id)=(d.workspace_id,d.child_task_id)
      WHERE d.workspace_id=NEW.workspace_id AND d.child_task_id=NEW.task_id
        AND d.child_attempt_id=NEW.attempt_id AND d.child_goal_id=NEW.goal_id
        AND d.source_task_id=parent_task AND d.source_attempt_id=NEW.parent_attempt_id
        AND d.source_checkpoint_id=NEW.source_checkpoint_id AND d.derivation_kind=NEW.cause
        AND source.owner_user_id=child.owner_user_id
    ) INTO ancestor_found;
  END IF;
  IF NOT ancestor_found THEN RAISE EXCEPTION 'research_attempt_source_lineage' USING ERRCODE='23503'; END IF;
  RETURN NEW;
END $$;


-- Stage4 explicitly creates independent tasks (parent_task_id IS NULL), with
-- their source recorded in immutable TaskDerivation. Keep parent-bound legacy
-- rows valid and require exact source attempt/checkpoint on independent rows.
ALTER TABLE shiliu.research_task_derivations DROP CONSTRAINT fk_parent_d1987ae131363965;
CREATE FUNCTION shiliu.validate_research_derivation_source() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM shiliu.research_tasks s
    JOIN shiliu.research_tasks c ON c.workspace_id=s.workspace_id AND c.owner_user_id=s.owner_user_id
    JOIN shiliu.research_attempts a ON (a.workspace_id,a.task_id,a.attempt_id)=(c.workspace_id,c.task_id,NEW.child_attempt_id)
    JOIN shiliu.research_checkpoints p ON (p.workspace_id,p.task_id,p.checkpoint_id)=(s.workspace_id,s.task_id,NEW.source_checkpoint_id)
    WHERE s.workspace_id=NEW.workspace_id AND s.task_id=NEW.source_task_id AND c.task_id=NEW.child_task_id
      AND (c.parent_task_id=s.task_id OR (c.parent_task_id IS NULL
        AND a.parent_attempt_id=NEW.source_attempt_id AND a.source_checkpoint_id=NEW.source_checkpoint_id
        AND a.cause=NEW.derivation_kind AND a.goal_id=NEW.child_goal_id
        AND p.attempt_id=NEW.source_attempt_id AND p.goal_id=NEW.source_goal_id))
  ) THEN RAISE EXCEPTION 'research_derivation_source_lineage' USING ERRCODE='23503'; END IF;
  RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER research_derivation_source_lineage
AFTER INSERT OR UPDATE ON shiliu.research_task_derivations DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW EXECUTE FUNCTION shiliu.validate_research_derivation_source();
